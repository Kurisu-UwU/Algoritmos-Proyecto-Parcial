void DibujarMiles(int x, int y) {
	Posicion(x+1, y); y++; cout << "__";
	Posicion(x, y); y++;  cout << "(\/)";
	Posicion(x, y); y++;  cout << "°||°";
	Posicion(x+1, y); y++; cout << "^^";
}
